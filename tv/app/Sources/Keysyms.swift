// atv-macos: VNC sends X11 keysyms; the virtual Mac's USB keyboard wants HID
// usages (US layout). A shifted symbol maps to its physical key: the viewer
// sends the Shift key itself.
//
// From a Windows keyboard: Windows key = Command, Alt = Option, Ctrl = Control.

enum Keysyms {
    static func hid(_ keysym: UInt32) -> UInt8? {
        switch keysym {
        case 0x61...0x7A: return UInt8(0x04 + keysym - 0x61)          // a-z
        case 0x41...0x5A: return UInt8(0x04 + keysym - 0x41)          // A-Z
        case 0x31...0x39: return UInt8(0x1E + keysym - 0x31)          // 1-9
        case 0x30: return 0x27                                        // 0
        case 0xFFBE...0xFFC9: return UInt8(0x3A + keysym - 0xFFBE)    // F1-F12
        case 0xFFCA...0xFFCD: return UInt8(0x68 + keysym - 0xFFCA)    // F13-F16
        case 0xFFB1...0xFFB9: return UInt8(0x59 + keysym - 0xFFB1)    // keypad 1-9
        default: return table[keysym]
        }
    }

    private static let table: [UInt32: UInt8] = [
        // shifted digits
        0x21: 0x1E, 0x40: 0x1F, 0x23: 0x20, 0x24: 0x21, 0x25: 0x22,
        0x5E: 0x23, 0x26: 0x24, 0x2A: 0x25, 0x28: 0x26, 0x29: 0x27,
        // punctuation, plain and shifted
        0x2D: 0x2D, 0x5F: 0x2D, 0x3D: 0x2E, 0x2B: 0x2E, 0x5B: 0x2F, 0x7B: 0x2F,
        0x5D: 0x30, 0x7D: 0x30, 0x5C: 0x31, 0x7C: 0x31, 0x3B: 0x33, 0x3A: 0x33,
        0x27: 0x34, 0x22: 0x34, 0x60: 0x35, 0x7E: 0x35, 0x2C: 0x36, 0x3C: 0x36,
        0x2E: 0x37, 0x3E: 0x37, 0x2F: 0x38, 0x3F: 0x38, 0x20: 0x2C,
        // editing and navigation
        0xFF0D: 0x28, 0xFF1B: 0x29, 0xFF08: 0x2A, 0xFF09: 0x2B, 0xFE20: 0x2B,
        0xFFE5: 0x39, 0xFF61: 0x46, 0xFF14: 0x47, 0xFF13: 0x48, 0xFF63: 0x49,
        0xFF50: 0x4A, 0xFF55: 0x4B, 0xFFFF: 0x4C, 0xFF57: 0x4D, 0xFF56: 0x4E,
        0xFF53: 0x4F, 0xFF51: 0x50, 0xFF54: 0x51, 0xFF52: 0x52,
        // keypad
        0xFF7F: 0x53, 0xFFAF: 0x54, 0xFFAA: 0x55, 0xFFAD: 0x56, 0xFFAB: 0x57,
        0xFF8D: 0x58, 0xFFB0: 0x62, 0xFFAE: 0x63, 0xFFBD: 0x67,
        // modifiers: Ctrl, Shift, Alt -> Option, Meta/Super (Windows key) -> Command
        0xFFE3: 0xE0, 0xFFE1: 0xE1, 0xFFE9: 0xE2, 0xFFE7: 0xE3, 0xFFEB: 0xE3,
        0xFFE4: 0xE4, 0xFFE2: 0xE5, 0xFFEA: 0xE6, 0xFFE8: 0xE7, 0xFFEC: 0xE7,
        0xFE03: 0xE6,   // ISO_Level3_Shift (AltGr) -> right Option
        0xFF67: 0x65,   // Menu -> Application
    ]
}
